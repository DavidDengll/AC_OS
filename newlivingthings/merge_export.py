# merge_export.py
# -*- coding: utf-8 -*-
"""
merge_export.py —— 第三步：基因融合与热替换的"融合"部分

流水线：
  1. 把 LoRA 适配器合并进基础模型（peft merge_and_unload -> 全量 safetensors）
  2. 转换为 GGUF（优先 Ollama 自带/本地 llama.cpp 的 convert_hf_to_gguf.py）
  3. 生成 Modelfile 并执行：ollama create entropy_evolved -f ./Modelfile

退出码：0 成功；非 0 失败（self_finetune.py 会打印 [进化失败] 并保住原大脑）。
本脚本不删除任何已有文件，只会新建产物。
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile

MODELFILE_TEMPLATE = """# Modelfile generated by entropy AC OS merge_export.py
# 基因融合产物：基底大脑 + LoRA 记忆
FROM {gguf}

TEMPLATE {{{{ .Prompt }}}}

PARAMETER temperature 0.7
PARAMETER top_p 0.95
PARAMETER top_k 20
"""


def log(msg):
    print(msg, flush=True)


def default_ollama_bin():
    try:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import config
        b = getattr(config, "OLLAMA_BIN", "ollama")
        if b and (shutil.which(b) or os.path.exists(b)):
            return b
    except Exception:
        pass
    found = shutil.which("ollama")
    if found:
        return found
    guess = os.path.expanduser(r"~\AppData\Local\Programs\Ollama\ollama.exe")
    return guess if os.path.exists(guess) else "ollama"


def merge_lora(base_model, adapter_dir, out_dir):
    """把 LoRA 权重合并进基底模型，返回合并后的 HF 目录。"""
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from peft import PeftModel
    import torch

    os.makedirs(out_dir, exist_ok=True)
    log("[融合] 加载基底大脑: %s" % base_model)
    tokenizer = AutoTokenizer.from_pretrained(base_model, trust_remote_code=True)
    model = AutoModelForCausalLM.from_pretrained(
        base_model, torch_dtype=torch.float32, trust_remote_code=True,
        low_cpu_mem_usage=True)
    log("[融合] 加载 LoRA 记忆: %s" % adapter_dir)
    model = PeftModel.from_pretrained(model, adapter_dir)
    log("[融合] merge_and_unload ...")
    model = model.merge_and_unload()
    model.save_pretrained(out_dir, safe_serialization=True)
    tokenizer.save_pretrained(out_dir)
    log("[融合] 已写出合并模型: %s" % out_dir)
    return out_dir


def find_gguf_converter(ollama_bin):
    """寻找 convert_hf_to_gguf.py：环境变量 > ollama 目录 > llama.cpp > PATH。"""
    env = os.environ.get("AC_GGUF_CONVERTER")
    if env and os.path.exists(env):
        return env
    cands = []
    if ollama_bin and os.path.exists(ollama_bin):
        root = os.path.dirname(ollama_bin)
        cands += [os.path.join(root, "convert_hf_to_gguf.py"),
                  os.path.join(root, "llama.cpp", "convert_hf_to_gguf.py")]
    for p in os.environ.get("PATH", "").split(os.pathsep):
        if p and ("llama" in p.lower() or "ollama" in p.lower()):
            cands.append(os.path.join(p, "convert_hf_to_gguf.py"))
    for c in cands:
        if os.path.exists(c):
            return c
    return None


def try_convert_gguf(hf_dir, out_gguf, ollama_bin):
    """把 HF 目录转成 GGUF。成功返回 gguf 路径，否则抛异常。"""
    converter = find_gguf_converter(ollama_bin)
    if not converter:
        raise RuntimeError(
            "未找到 convert_hf_to_gguf.py（llama.cpp / Ollama 未提供）。"
            "可设置环境变量 AC_GGUF_CONVERTER 指向该脚本。")
    cmd = [sys.executable, converter, hf_dir, "--outfile", out_gguf, "--outtype", "q8_0"]
    log("[GGUF] " + " ".join(cmd))
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0 or not os.path.exists(out_gguf):
        raise RuntimeError("GGUF 转换失败: %s" % (r.stderr or r.stdout)[-400:])
    log("[GGUF] 已生成: %s" % out_gguf)
    return out_gguf


def write_modelfile(path, from_ref):
    text = MODELFILE_TEMPLATE.format(gguf=from_ref)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    log("[Modelfile] 已生成: %s" % path)
    return path


def ollama_create(ollama_bin, name, modelfile):
    cmd = [ollama_bin, "create", name, "-f", modelfile]
    log("[Ollama] " + " ".join(cmd))
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=1800)
    if r.returncode != 0:
        raise RuntimeError("ollama create 失败: %s" % (r.stderr or r.stdout)[-400:])
    log("[Ollama] 新大脑注册成功: %s" % name)
    return True


def parse_args(argv=None):
    p = argparse.ArgumentParser(description="LoRA 合并与 Ollama 注册")
    p.add_argument("--adapter", required=True)
    p.add_argument("--base-model", required=True)
    p.add_argument("--output-dir", required=True)
    p.add_argument("--name", default="entropy_evolved")
    p.add_argument("--ollama-create", action="store_true")
    p.add_argument("--ollama-bin", default=None)
    p.add_argument("--skip-gguf", action="store_true",
                   help="只合并，不转 GGUF（用于本机无转换器的场景）")
    return p.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    registry = os.path.join(args.output_dir, "merge_result.json")

    def save(payload):
        try:
            os.makedirs(args.output_dir, exist_ok=True)
            with open(registry, "w", encoding="utf-8") as f:
                json.dump(payload, f, ensure_ascii=False, indent=2)
        except Exception:
            pass

    if not os.path.exists(os.path.join(args.adapter, "adapter_config.json")):
        save({"status": "failed", "stage": "precheck",
              "error": "适配器目录缺少 adapter_config.json: %s" % args.adapter})
        log("[融合失败] 适配器不完整")
        return 3

    try:
        merged = merge_lora(args.base_model, args.adapter, args.output_dir)
    except ImportError as e:
        save({"status": "failed", "stage": "merge", "kind": "dependency", "error": str(e)})
        log("[融合失败] 缺少依赖: %s" % e)
        return 4
    except Exception as e:
        save({"status": "failed", "stage": "merge", "error": str(e)})
        log("[融合失败] %s: %s" % (type(e).__name__, e))
        return 1

    gguf_path = None
    if not args.skip_gguf:
        ollama_bin = args.ollama_bin or default_ollama_bin()
        gguf_out = os.path.join(args.output_dir, args.name + ".gguf")
        try:
            gguf_path = try_convert_gguf(merged, gguf_out, ollama_bin)
        except Exception as e:
            save({"status": "failed", "stage": "gguf", "merged": merged, "error": str(e)})
            log("[融合失败] GGUF 阶段: %s" % e)
            return 5

        if args.ollama_create:
            modelfile = write_modelfile(os.path.join(args.output_dir, "Modelfile"), gguf_path)
            try:
                ollama_create(ollama_bin, args.name, modelfile)
            except Exception as e:
                save({"status": "failed", "stage": "ollama", "merged": merged,
                      "gguf": gguf_path, "modelfile": modelfile, "error": str(e)})
                log("[融合失败] Ollama 注册阶段: %s" % e)
                return 6

    save({"status": "ok", "merged": merged, "gguf": gguf_path, "name": args.name})
    log("[融合] 全部完成")
    return 0


if __name__ == "__main__":
    sys.exit(main())
