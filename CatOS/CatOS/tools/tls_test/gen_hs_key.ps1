# tools/tls_test/gen_hs_key.ps1
#
# 生成握手测试用的 RSA-2048 密钥对:
#   hs_key.txt  -> n / e / d (十六进制, 每行 key=value), 供 server_emu.py 解密密文
#   hs_pub.h    -> 供 C 测试使用的 n / e
#
# 密文解密由 Python 用 pow(c, d, n) 完成 (Python 整数天然支持大数).

param([string]$KeyFile = "hs_key.txt", [string]$HeaderFile = "hs_pub.h")

$ErrorActionPreference = "Stop"

$rsa = [System.Security.Cryptography.RSA]::Create(2048)
$priv = $rsa.ExportParameters($true)
$pub = $rsa.ExportParameters($false)

function To-Hex([byte[]]$b) {
    return (($b | ForEach-Object { $_.ToString("x2") }) -join "")
}

$lines = @(
    ("n=" + (To-Hex $pub.Modulus)),
    ("e=" + (To-Hex $pub.Exponent)),
    ("d=" + (To-Hex $priv.D))
)
[System.IO.File]::WriteAllLines((Resolve-Path -LiteralPath ".").Path + "\" + $KeyFile, $lines,
                                (New-Object System.Text.UTF8Encoding($false)))

$hdr = @(
    "/* generated by gen_hs_key.ps1 - do not edit */",
    "#ifndef _HS_PUB_H_",
    "#define _HS_PUB_H_",
    ("static const char *hs_n_hex = """ + (To-Hex $pub.Modulus) + """;"),
    ("static const char *hs_e_hex = """ + (To-Hex $pub.Exponent) + """;"),
    ("#define HS_N_LEN " + $pub.Modulus.Length),
    "#endif"
)
[System.IO.File]::WriteAllLines((Resolve-Path -LiteralPath ".").Path + "\" + $HeaderFile, $hdr,
                                (New-Object System.Text.UTF8Encoding($false)))

Write-Host ("written: {0}, {1} (n={2} bytes)" -f $KeyFile, $HeaderFile, $pub.Modulus.Length)
