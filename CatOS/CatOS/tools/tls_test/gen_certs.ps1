# tools/tls_test/gen_certs.ps1
#
# 用 .NET 生成 X.509 测试证书链 (RSA-2048 / SHA-256):
#   root     : 自签 CA
#   leaf     : 由 root 签发, 有效期覆盖今天
#   expired  : 由 root 签发, 但已过期
# 输出 certs.h (DER 十六进制 + 当前日期), 供 C 侧解析/验链.

param([string]$OutFile = "certs.h")

$ErrorActionPreference = "Stop"

function To-Hex([byte[]]$b) {
    return (($b | ForEach-Object { $_.ToString("x2") }) -join "")
}

$hash = [System.Security.Cryptography.HashAlgorithmName]::SHA256
$pad = [System.Security.Cryptography.RSASignaturePadding]::Pkcs1
$now = [System.DateTimeOffset]::UtcNow

# ---------- 根证书 ----------
$rootKey = [System.Security.Cryptography.RSA]::Create(2048)
$rootReq = [System.Security.Cryptography.X509Certificates.CertificateRequest]::new(
    "CN=CatOS Test Root", $rootKey, $hash, $pad)
$caExt = [System.Security.Cryptography.X509Certificates.X509BasicConstraintsExtension]::new(
    $true, $false, 0, $true)
$rootReq.CertificateExtensions.Add($caExt)
$root = $rootReq.CreateSelfSigned($now.AddDays(-10), $now.AddYears(5))

# 确保带私钥, 供签发用
try {
    $rootWithKey = $root.CopyWithPrivateKey($rootKey)
    if ($rootWithKey) { $root = $rootWithKey }
} catch {
    Write-Host "  note: CopyWithPrivateKey unavailable, using CreateSelfSigned result"
}

# ---------- 叶子证书 (有效) ----------
$leafKey = [System.Security.Cryptography.RSA]::Create(2048)
$leafReq = [System.Security.Cryptography.X509Certificates.CertificateRequest]::new(
    "CN=catos.test", $leafKey, $hash, $pad)
$serial1 = [byte[]](1, 2, 3, 4, 5, 6, 7, 8)
$leaf = $leafReq.Create($root, $now.AddDays(-1), $now.AddDays(30), $serial1)

# ---------- 叶子证书 (已过期, 但签发者仍然有效) ----------
# 有效期必须落在根证书的 notBefore 之后、当前时间之前
$expKey = [System.Security.Cryptography.RSA]::Create(2048)
$expReq = [System.Security.Cryptography.X509Certificates.CertificateRequest]::new(
    "CN=expired.catos.test", $expKey, $hash, $pad)
$serial2 = [byte[]](9, 9, 9, 9, 9, 9, 9, 9)
$expired = $expReq.Create($root, $now.AddDays(-9), $now.AddDays(-5), $serial2)

$ct = [System.Security.Cryptography.X509Certificates.X509ContentType]::Cert
$rootDer = $root.Export($ct)
$leafDer = $leaf.Export($ct)
$expDer = $expired.Export($ct)


$lines = @(
    "/* generated by gen_certs.ps1 (.NET X509Certificate2) - do not edit */",
    "#ifndef _CERTS_H_",
    "#define _CERTS_H_",
    ("static const char *cert_root_hex = """ + (To-Hex $rootDer) + """;"),
    ("static const char *cert_leaf_hex = """ + (To-Hex $leafDer) + """;"),
    ("static const char *cert_expired_hex = """ + (To-Hex $expDer) + """;"),
    ("#define CERT_NOW_YEAR  " + $now.Year),
    ("#define CERT_NOW_MONTH " + $now.Month),
    ("#define CERT_NOW_DAY   " + $now.Day),
    ("#define CERT_ROOT_LEN  " + $rootDer.Length),
    ("#define CERT_LEAF_LEN  " + $leafDer.Length),
    "#endif"
)

[System.IO.File]::WriteAllLines((Resolve-Path -LiteralPath ".").Path + "\" + $OutFile, $lines,
                                (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("written: {0} (root {1} B, leaf {2} B, expired {3} B)" -f `
            $OutFile, $rootDer.Length, $leafDer.Length, $expDer.Length)
# ---------- 给 Python 侧用的文本版 (含叶子私钥, 仅测试用) ----------
$leafPriv = $leafKey.ExportParameters($true)
function To-HexB([byte[]]$b) { return (($b | ForEach-Object { $_.ToString("x2") }) -join "") }
$pyLines = @(
    ("root=" + (To-Hex $rootDer)),
    ("leaf=" + (To-Hex $leafDer)),
    ("leaf_n=" + (To-HexB $leafPriv.Modulus)),
    ("leaf_e=" + (To-HexB $leafPriv.Exponent)),
    ("leaf_d=" + (To-HexB $leafPriv.D)),
    ("now_y=" + $now.Year),
    ("now_m=" + $now.Month),
    ("now_d=" + $now.Day)
)
[System.IO.File]::WriteAllLines((Resolve-Path -LiteralPath ".").Path + "\certs_py.txt", $pyLines,
                                (New-Object System.Text.UTF8Encoding($false)))
Write-Host "written: certs_py.txt"