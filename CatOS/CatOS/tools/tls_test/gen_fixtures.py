#!/usr/bin/env python3
"""Generate TLS 1.2 server-side fixtures with an independent record framing.

This is deliberately a *separate* implementation of TLS record/handshake
framing from lib/tls.c, so the C parser is checked against something that was
not derived from it.

Output: fixtures.h
  - fixture_records_hex   : hex of the server's record stream
  - FIX_*  expected values: version, cipher suite, certificate count/length
"""

import sys

HANDSHAKE = 22


def record(ctype, payload):
    return bytes([ctype, 3, 3, (len(payload) >> 8) & 0xFF, len(payload) & 0xFF]) + payload


def hs(mtype, body):
    return bytes([mtype]) + len(body).to_bytes(3, "big") + body


def main():
    # ---- ServerHello: TLS1.2, empty session id, suite 0x009C, null compression
    server_random = bytes(((i * 7 + 3) % 256) for i in range(32))
    suite = 0x009C
    sh = bytes([3, 3]) + server_random + bytes([0])
    sh += suite.to_bytes(2, "big")
    sh += bytes([0])                      # compression: null
    sh += bytes([0, 0])                   # extensions length = 0

    # ---- Certificate: one fake 512-byte certificate
    der = bytes(((i * 13 + 5) % 256) for i in range(512))
    cert_entry = len(der).to_bytes(3, "big") + der
    cert_body = len(cert_entry).to_bytes(3, "big") + cert_entry

    # ---- Two records:
    #   1) ServerHello alone
    #   2) Certificate + ServerHelloDone in ONE record (multiple handshake
    #      messages per record is legal and a good parser test)
    rec1 = record(HANDSHAKE, hs(2, sh))
    rec2 = record(HANDSHAKE, hs(11, cert_body) + hs(14, b""))

    stream = rec1 + rec2

    out = []
    out.append("/* generated by gen_fixtures.py (independent TLS framing) - do not edit */")
    out.append("#ifndef _FIXTURES_H_")
    out.append("#define _FIXTURES_H_")
    out.append('static const char *fixture_records_hex = "%s";' % stream.hex())
    out.append("#define FIX_VERSION_MAJOR   %d" % 3)
    out.append("#define FIX_VERSION_MINOR   %d" % 3)
    out.append("#define FIX_SUITE           0x%04X" % suite)
    out.append("#define FIX_SERVER_RANDOM_HEX \"%s\"" % server_random.hex())
    out.append("#define FIX_CERT_COUNT      %d" % 1)
    out.append("#define FIX_CERT_LEN        %d" % len(der))
    out.append("#define FIX_CERT_HEX        \"%s\"" % der.hex())
    out.append("#define FIX_RECORD_COUNT    %d" % 2)
    out.append("#define FIX_HANDSHAKE_COUNT %d" % 3)
    out.append("#endif")

    text = "\n".join(out) + "\n"
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("written: %s (%d bytes, stream %d bytes)" % (sys.argv[1], len(text), len(stream)))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
