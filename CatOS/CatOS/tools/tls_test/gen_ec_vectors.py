#!/usr/bin/env python3
"""Independent P-256 reference in pure Python, used to generate vectors for
lib/ec.c (field arithmetic, point multiplication, ECDH).

Output: ec_vectors.h
"""

import sys

P = 2**256 - 2**224 + 2**192 + 2**96 - 1
A = -3 % P
B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5
N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551


def inv(x):
    return pow(x % P, P - 2, P)


def padd(p1, p2):
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2 and (y1 + y2) % P == 0:
        return None
    if p1 == p2:
        lam = (3 * x1 * x1 + A) * inv(2 * y1) % P
    else:
        lam = (y2 - y1) * inv(x2 - x1) % P
    x3 = (lam * lam - x1 - x2) % P
    y3 = (lam * (x1 - x3) - y1) % P
    return (x3, y3)


def pmul(k, pt):
    r = None
    addend = pt
    while k:
        if k & 1:
            r = padd(r, addend)
        addend = padd(addend, addend)
        k >>= 1
    return r


def hx(v, n=32):
    return v.to_bytes(n, "big").hex()


def main():
    cases_add = []
    cases_mul = []
    cases_inv = []

    for i in range(3):
        a = (0x11 + i * 0x0101010101010101) % P
        b = (0x9E3779B97F4A7C15 >> (i * 4)) % P
        cases_add.append((a, b, (a + b) % P, (a - b) % P, a * b % P))
        cases_inv.append((a, inv(a)))

    # 大数样本: 接近 p 的值
    a = P - 3
    b = P - 5
    cases_add.append((a, b, (a + b) % P, (a - b) % P, a * b % P))
    cases_inv.append((a, inv(a)))

    G = (GX, GY)
    for k in (2, 3, 7, 0x1234567890ABCDEF):
        q = pmul(k, G)
        cases_mul.append((k, q[0], q[1]))

    # ECDH: 两方私钥与共享点
    d1 = 0x0A0B0C0D0E0F101112131415161718191A1B1C1D1E1F2021222324252627 % N
    d2 = 0x112233445566778899AABBCCDDEEFF00112233445566778899AABBCCDDEEFF % N
    q1 = pmul(d1, G)
    q2 = pmul(d2, G)
    shared = pmul(d1 * d2 % N, G)

    out = []
    out.append("/* generated by gen_ec_vectors.py (independent Python P-256) */")
    out.append("#ifndef _EC_VECTORS_H_")
    out.append("#define _EC_VECTORS_H_")
    out.append("typedef struct { const char *a; const char *b; const char *add; const char *sub; const char *mul; } EC_FE_VEC;")
    out.append("typedef struct { const char *a; const char *inv; } EC_INV_VEC;")
    out.append("typedef struct { const char *k; const char *qx; const char *qy; } EC_MUL_VEC;")
    out.append("typedef struct { const char *d1; const char *d2; const char *q1x; const char *q1y;"
               " const char *q2x; const char *q2y; const char *shared; } EC_ECDH_VEC;")
    out.append("")
    out.append("static const EC_FE_VEC ec_fe_vecs[] = {")
    for a, b, add, sub, mul in cases_add:
        out.append('  { "%s", "%s", "%s", "%s", "%s" },' % (hx(a), hx(b), hx(add), hx(sub), hx(mul)))
    out.append("};")
    out.append("")
    out.append("static const EC_INV_VEC ec_inv_vecs[] = {")
    for a, i in cases_inv:
        out.append('  { "%s", "%s" },' % (hx(a), hx(i)))
    out.append("};")
    out.append("")
    out.append("static const EC_MUL_VEC ec_mul_vecs[] = {")
    for k, qx, qy in cases_mul:
        out.append('  { "%s", "%s", "%s" },' % (hx(k, 32), hx(qx), hx(qy)))
    out.append("};")
    out.append("")
    out.append("static const EC_ECDH_VEC ec_ecdh_vecs[] = {")
    out.append('  { "%s", "%s", "%s", "%s", "%s", "%s", "%s" },' % (
        hx(d1), hx(d2), hx(q1[0]), hx(q1[1]), hx(q2[0]), hx(q2[1]), hx(shared[0])))
    out.append("};")
    out.append("")
    out.append('#define EC_GX_HEX "%s"' % hx(GX))
    out.append('#define EC_GY_HEX "%s"' % hx(GY))
    out.append("")
    out.append("#endif")

    text = "\n".join(out) + "\n"
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("written: %s (%d bytes)" % (sys.argv[1], len(text)))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
