#!/usr/bin/env python3
"""Generate test vectors for lib/crypto.c from Python's hashlib/hmac.

Usage: python gen_vectors.py > expected.h
The generated header is included by test.c.
"""

import hashlib
import hmac
import sys


def p_hash(secret, seed, length):
    """TLS 1.2 P_SHA256 (RFC 5246 section 5)."""
    out = b""
    a = hmac.new(secret, seed, hashlib.sha256).digest()
    while len(out) < length:
        out += hmac.new(secret, a + seed, hashlib.sha256).digest()
        a = hmac.new(secret, a, hashlib.sha256).digest()
    return out[:length]


def prf(secret, label, seed, length):
    return p_hash(secret, label.encode() + seed, length)


def hexs(b):
    return "".join("%02x" % c for c in b)


def c_str(s):
    return '"' + s.replace('"', '\\"') + '"'


def main():
    sha_cases = [
        ("empty", b""),
        ("abc", b"abc"),
        ("two_blocks", b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
        ("55_bytes", b"a" * 55),
        ("56_bytes", b"a" * 56),
        ("63_bytes", b"a" * 63),
        ("64_bytes", b"a" * 64),
        ("65_bytes", b"a" * 65),
        ("128_bytes", b"a" * 128),
        ("1000_bytes", bytes([i % 251 for i in range(1000)])),
        ("quick_brown_fox", b"The quick brown fox jumps over the lazy dog"),
    ]

    hmac_cases = [
        ("key=key,data=empty", b"key", b""),
        ("key=key,data=quick", b"key", b"The quick brown fox jumps over the lazy dog"),
        ("key=64bytes", b"k" * 64, b"hello"),
        ("key=100bytes(hash first)", b"K" * 100, b"hello"),
        ("key=empty", b"", b"data"),
    ]

    prf_cases = [
        ("master_secret_48", bytes(range(48)), "master secret", bytes(range(64, 128)), 48),
        ("master_secret_odd", bytes(range(32)), "master secret", bytes(range(64)), 100),
        ("key_expansion", bytes(range(48)), "key expansion", bytes(range(64)), 72),
        ("long_out", b"secret", "client finished", bytes(range(32)), 256),
    ]

    out = []
    out.append("/* generated by gen_vectors.py (Python hashlib/hmac) - do not edit */")
    out.append("#ifndef _EXPECTED_H_")
    out.append("#define _EXPECTED_H_")
    out.append("")
    out.append("typedef struct { const char *name; const char *in_hex; const char *out_hex; } SHA_VEC;")
    out.append("typedef struct { const char *name; const char *key_hex; const char *in_hex; const char *out_hex; } HMAC_VEC;")
    out.append("typedef struct { const char *name; const char *secret_hex; const char *label; const char *seed_hex; int out_len; const char *out_hex; } PRF_VEC;")
    out.append("")

    out.append("static const SHA_VEC sha_vecs[] = {")
    for name, data in sha_cases:
        out.append("  { %s, %s, %s }," % (c_str(name), c_str(hexs(data)), c_str(hashlib.sha256(data).hexdigest())))
    out.append("};")
    out.append("")

    out.append("static const HMAC_VEC hmac_vecs[] = {")
    for name, key, data in hmac_cases:
        mac = hmac.new(key, data, hashlib.sha256).hexdigest()
        out.append("  { %s, %s, %s, %s }," % (c_str(name), c_str(hexs(key)), c_str(hexs(data)), c_str(mac)))
    out.append("};")
    out.append("")

    out.append("static const PRF_VEC prf_vecs[] = {")
    for name, secret, label, seed, length in prf_cases:
        data = prf(secret, label, seed, length)
        out.append("  { %s, %s, %s, %s, %d, %s }," % (
            c_str(name), c_str(hexs(secret)), c_str(label), c_str(hexs(seed)),
            length, c_str(data.hex())))
    out.append("};")
    out.append("")
    out.append("#endif")
    out.append("")

    text = "\n".join(out) + "\n"
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("written: %s (%d bytes)" % (sys.argv[1], len(text)))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
