# tools/crypto_test/gen_vectors_net.ps1
#
# 用 .NET 的密码学实现生成 AES-128 / SHA-1 / HMAC-SHA1 / AES-GCM 测试向量,
# 输出 expected_net.h 供 test.c 使用 (独立实现交叉验证, 不依赖 Python 的 AES).
#
# 用法:  pwsh -File gen_vectors_net.ps1 > expected_net.h   (或用下面的 -OutFile)

param(
    [string]$OutFile = "expected_net.h"
)

$ErrorActionPreference = "Stop"

function To-Hex([byte[]]$b) {
    if ($null -eq $b) { return "" }
    return (($b | ForEach-Object { $_.ToString("x2") }) -join "")
}

function From-Hex([string]$h) {
    $n = [int]($h.Length / 2)
    $r = New-Object byte[] $n
    for ($i = 0; $i -lt $n; $i++) {
        $r[$i] = [Convert]::ToByte($h.Substring($i * 2, 2), 16)
    }
    return $r
}

function New-Bytes([int[]]$vals) {
    $r = New-Object byte[] $vals.Length
    for ($i = 0; $i -lt $vals.Length; $i++) { $r[$i] = [byte]$vals[$i] }
    return $r
}

function Bytes-Of([int]$n, [int]$start = 0) {
    $r = New-Object byte[] $n
    for ($i = 0; $i -lt $n; $i++) { $r[$i] = [byte](($start + $i) % 251) }
    return $r
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("/* generated by gen_vectors_net.ps1 (.NET crypto) - do not edit */")
$lines.Add("#ifndef _EXPECTED_NET_H_")
$lines.Add("#define _EXPECTED_NET_H_")
$lines.Add("")

# ---------- SHA-1 ----------
$sha1Cases = @(
    @("empty", (New-Object byte[] 0)),
    @("abc", [System.Text.Encoding]::ASCII.GetBytes("abc")),
    @("55_bytes", (New-Bytes (1..55 | ForEach-Object { 97 }))),
    @("56_bytes", (New-Bytes (1..56 | ForEach-Object { 97 }))),
    @("64_bytes", (New-Bytes (1..64 | ForEach-Object { 97 }))),
    @("65_bytes", (New-Bytes (1..65 | ForEach-Object { 97 }))),
    @("1000_bytes", (Bytes-Of 1000))
)
$lines.Add("static const SHA1_VEC sha1_vecs[] = {")
foreach ($c in $sha1Cases) {
    $sha1 = [System.Security.Cryptography.SHA1]::Create()
    $d = $sha1.ComputeHash($c[1])
    $lines.Add(("  {{ `"{0}`", `"{1}`", `"{2}`" }}," -f $c[0], (To-Hex $c[1]), (To-Hex $d)))
}
$lines.Add("};")
$lines.Add("")

# ---------- HMAC-SHA1 ----------
$hmac1Cases = @(
    @("key=key,empty", [System.Text.Encoding]::ASCII.GetBytes("key"), (New-Object byte[] 0)),
    @("key=key,data", [System.Text.Encoding]::ASCII.GetBytes("key"), [System.Text.Encoding]::ASCII.GetBytes("The quick brown fox")),
    @("key=64bytes", (New-Bytes (1..64 | ForEach-Object { 107 })), [System.Text.Encoding]::ASCII.GetBytes("hello")),
    @("key=100bytes", (New-Bytes (1..100 | ForEach-Object { 75 })), [System.Text.Encoding]::ASCII.GetBytes("hello"))
)
$lines.Add("static const HMAC_VEC hmac1_vecs[] = {")
foreach ($c in $hmac1Cases) {
    $h = [System.Security.Cryptography.HMACSHA1]::new($c[1])
    $d = $h.ComputeHash($c[2])
    $lines.Add(("  {{ `"{0}`", `"{1}`", `"{2}`", `"{3}`" }}," -f $c[0], (To-Hex $c[1]), (To-Hex $c[2]), (To-Hex $d)))
}
$lines.Add("};")
$lines.Add("")

# ---------- AES-128 单分组 (FIPS-197 附录 C.1) ----------
$fipsKey = From-Hex "000102030405060708090a0b0c0d0e0f"
$fipsPt = From-Hex "00112233445566778899aabbccddeeff"
$aesE = [System.Security.Cryptography.Aes]::Create()
$aesE.Mode = "ECB"
$aesE.Padding = "None"
$aesE.Key = $fipsKey
$fipsCt = $aesE.CreateEncryptor().TransformFinalBlock($fipsPt, 0, 16)
$lines.Add("static const AES_VEC aes_ecb_vecs[] = {")
$lines.Add(("  {{ `"fips197_c1`", `"{0}`", `"{1}`", `"{2}`" }}," -f (To-Hex $fipsKey), (To-Hex $fipsPt), (To-Hex $fipsCt)))
$lines.Add("};")
$lines.Add("")

# ---------- AES-128-CBC (多分组) ----------
$cbcKey = Bytes-Of 16 0
$cbcIv = Bytes-Of 16 16
$cbcPt = Bytes-Of 64 32
$aesC = [System.Security.Cryptography.Aes]::Create()
$aesC.Mode = "CBC"
$aesC.Padding = "None"
$aesC.Key = $cbcKey
$aesC.IV = $cbcIv
$cbcCt = $aesC.CreateEncryptor().TransformFinalBlock($cbcPt, 0, 64)
$lines.Add("static const AES_CBC_VEC aes_cbc_vecs[] = {")
$lines.Add(("  {{ `"cbc_64b`", `"{0}`", `"{1}`", `"{2}`", `"{3}`" }}," -f (To-Hex $cbcKey), (To-Hex $cbcIv), (To-Hex $cbcPt), (To-Hex $cbcCt)))
$lines.Add("};")
$lines.Add("")

# ---------- AES-128-CTR (用 ECB 手工拼 keystream) ----------
$ctrKey = Bytes-Of 16 1
$ctrNonce = Bytes-Of 16 2
$ctrPt = Bytes-Of 48 3
$ecbEnc = [System.Security.Cryptography.Aes]::Create()
$ecbEnc.Mode = "ECB"
$ecbEnc.Padding = "None"
$ecbEnc.Key = $ctrKey
$enc = $ecbEnc.CreateEncryptor()
$ks = New-Object byte[] 48
$ctr = [byte[]]$ctrNonce.Clone()
for ($b = 0; $b -lt 3; $b++) {
    $blk = $enc.TransformFinalBlock($ctr, 0, 16)
    for ($i = 0; $i -lt 16; $i++) { $ks[$b * 16 + $i] = $blk[$i] }
    for ($i = 15; $i -ge 0; $i--) { $ctr[$i] = [byte](($ctr[$i] + 1) -band 0xFF); if ($ctr[$i] -ne 0) { break } }
}
$ctrCt = New-Object byte[] 48
for ($i = 0; $i -lt 48; $i++) { $ctrCt[$i] = [byte]($ctrPt[$i] -bxor $ks[$i]) }
$lines.Add("static const AES_CBC_VEC aes_ctr_vecs[] = {")
$lines.Add(("  {{ `"ctr_48b`", `"{0}`", `"{1}`", `"{2}`", `"{3}`" }}," -f (To-Hex $ctrKey), (To-Hex $ctrNonce), (To-Hex $ctrPt), (To-Hex $ctrCt)))
$lines.Add("};")
$lines.Add("")

# GCM 向量由 gen_gcm_vectors.py 生成 (.NET Framework 4.x 没有 AesGcm)
$lines.Add("#endif")
[System.IO.File]::WriteAllLines((Resolve-Path -LiteralPath ".").Path + "\" + $OutFile, $lines, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "written: $OutFile ($((Get-Item $OutFile).Length) bytes)"