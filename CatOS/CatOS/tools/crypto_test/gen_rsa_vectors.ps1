# tools/crypto_test/gen_rsa_vectors.ps1
#
# Generate RSA-2048 test vectors with .NET (independent implementation):
#   * modpow vectors        : BigInteger.ModPow
#   * signature vectors     : RSA.SignHash(Pkcs1, SHA256)
#   * encryption vectors    : fixed PKCS#1 v1.5 padding, expected EM and ciphertext
#
# Usage: powershell -File gen_rsa_vectors.ps1 -OutFile expected_rsa.h

param([string]$OutFile = "expected_rsa.h")

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Numerics
Add-Type -AssemblyName mscorlib

function To-Hex([byte[]]$b) {
    if ($null -eq $b) { return "" }
    return (($b | ForEach-Object { $_.ToString("x2") }) -join "")
}

function From-Hex([string]$h) {
    $n = [int]($h.Length / 2)
    $r = New-Object byte[] $n
    for ($i = 0; $i -lt $n; $i++) { $r[$i] = [Convert]::ToByte($h.Substring($i * 2, 2), 16) }
    return $r
}

# big-endian bytes -> positive BigInteger
function To-Big([byte[]]$b) {
    $le = [byte[]]($b.Clone())
    [Array]::Reverse($le)
    if ($le.Length -gt 0 -and ($le[$le.Length - 1] -band 0x80)) {
        $tmp = New-Object byte[] ($le.Length + 1)
        [Array]::Copy($le, $tmp, $le.Length)
        $le = $tmp
    } elseif ($le.Length -eq 0) {
        $le = New-Object byte[] 1
    }
    return [System.Numerics.BigInteger]::new($le)
}

# positive BigInteger -> big-endian bytes, fixed length
function From-Big([System.Numerics.BigInteger]$v, [int]$len) {
    $le = $v.ToByteArray()
    $be = [byte[]]($le.Clone())
    [Array]::Reverse($be)
    # strip leading sign byte(s)
    while ($be.Length -gt $len) {
        $be = $be[1..($be.Length - 1)]
        if ($be.Length -eq 1) { break }
    }
    $out = New-Object byte[] $len
    $copy = [Math]::Min($be.Length, $len)
    if ($copy -gt 0) {
        [Array]::Copy($be, $be.Length - $copy, $out, $len - $copy, $copy)
    }
    return $out
}

$rsa = [System.Security.Cryptography.RSA]::Create(2048)
$p = $rsa.ExportParameters($false)
$n = $p.Modulus
$eBytes = $p.Exponent
$eInt = 0
foreach ($b in $eBytes) { $eInt = ($eInt * 256) + $b }

$nBig = To-Big $n
$eBig = [System.Numerics.BigInteger]::new([int]$eInt)
$nLen = $n.Length

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("/* generated by gen_rsa_vectors.ps1 (.NET RSA / BigInteger) - do not edit */")
$lines.Add("#ifndef _EXPECTED_RSA_H_")
$lines.Add("#define _EXPECTED_RSA_H_")
$lines.Add("")
$lines.Add(("static const char *rsa_n_hex = `"{0}`";" -f (To-Hex $n)))
$lines.Add(("static const char *rsa_e_hex = `"{0}`";" -f (To-Hex $eBytes)))
$lines.Add(("static const int   rsa_n_len = {0};" -f $nLen))
$lines.Add("")

# ---- modpow vectors ----
$lines.Add("static const RSA_MODPOW_VEC rsa_modpow_vecs[] = {")
for ($i = 0; $i -lt 3; $i++) {
    $base = New-Object byte[] $nLen
    for ($k = 0; $k -lt $nLen; $k++) { $base[$k] = [byte]((($i + 1) * 37 + $k * 11) % 251 + 1) }
    $base[0] = 0                                   # keep it below n
    $baseBig = To-Big $base
    $want = [System.Numerics.BigInteger]::ModPow($baseBig, $eBig, $nBig)
    $wantBytes = From-Big $want $nLen
    $lines.Add(("  {{ `"modpow_{0}`", `"{1}`", `"{2}`" }}," -f $i, (To-Hex $base), (To-Hex $wantBytes)))
}
$lines.Add("};")
$lines.Add("")

# ---- signature vectors ----
$lines.Add("static const RSA_SIG_VEC rsa_sig_vecs[] = {")
for ($i = 0; $i -lt 2; $i++) {
    $msg = [System.Text.Encoding]::ASCII.GetBytes("CatOS TLS test message #$i")
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $hash = $sha.ComputeHash($msg)
    $sig = $rsa.SignHash($hash, [System.Security.Cryptography.HashAlgorithmName]::SHA256,
                         [System.Security.Cryptography.RSASignaturePadding]::Pkcs1)
    $lines.Add(("  {{ `"sig_{0}`", `"{1}`", `"{2}`" }}," -f $i, (To-Hex $hash), (To-Hex $sig)))
}
$lines.Add("};")
$lines.Add("")

# ---- encryption vectors (fixed padding, deterministic) ----
$msgLen = 48                                       # TLS pre-master secret size
$psLen = $nLen - 3 - $msgLen
$msg = New-Object byte[] $msgLen
$ps = New-Object byte[] $psLen
for ($k = 0; $k -lt $msgLen; $k++) { $msg[$k] = [byte](($k * 7 + 3) % 256) }
for ($k = 0; $k -lt $psLen; $k++) { $ps[$k] = [byte]((($k * 13 + 1) % 255) + 1) }   # non-zero

$em = New-Object byte[] $nLen
$em[0] = 0
$em[1] = 2
[Array]::Copy($ps, 0, $em, 2, $psLen)
$em[2 + $psLen] = 0
[Array]::Copy($msg, 0, $em, 3 + $psLen, $msgLen)

$emBig = To-Big $em
$ctBig = [System.Numerics.BigInteger]::ModPow($emBig, $eBig, $nBig)
$ct = From-Big $ctBig $nLen

$lines.Add("static const RSA_ENC_VEC rsa_enc_vecs[] = {")
$lines.Add(("  {{ `"v15_pms48`", `"{0}`", `"{1}`", `"{2}`", `"{3}`" }}," -f `
            (To-Hex $msg), (To-Hex $ps), (To-Hex $em), (To-Hex $ct)))
$lines.Add("};")
$lines.Add("")
$lines.Add("#endif")

[System.IO.File]::WriteAllLines((Resolve-Path -LiteralPath ".").Path + "\" + $OutFile, $lines,
                                (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("written: {0} ({1} bytes, n={2} bytes, e={3})" -f $OutFile, (Get-Item $OutFile).Length, $nLen, $eInt)
